"""Behaviour tests for evals/make_fixtures.py: the payouts PDF eval fixture.

The fixture is committed to a public repo and regenerated by contributors, so it must
build the same way on any OS and carry nothing about the machine that built it.
Tests that need a missing tool (fpdf2, pdftotext) are skipped rather than failed.
"""

import shutil
import sys
from pathlib import Path

import pytest

pytest.importorskip(
    "fpdf", reason="fpdf2 is needed to build the PDF fixture: pip install fpdf2"
)

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "evals"))
sys.path.insert(0, str(ROOT / "scripts"))
import extract  # noqa: E402
import make_fixtures  # noqa: E402

MACHINE_MARKERS = [b"macOS", b"Mac OS", b"Darwin", b"Build ", b"Quartz", b"cupsfilter"]


def _build(tmp_path: Path, name: str) -> Path:
    out = tmp_path / name
    out.mkdir()
    return make_fixtures.payouts_pdf(out)


def test_payouts_pdf_records_nothing_about_the_build_machine(tmp_path):
    raw = _build(tmp_path, "a").read_bytes()
    assert [m for m in MACHINE_MARKERS if m in raw] == []


def test_payouts_pdf_is_byte_identical_across_builds(tmp_path):
    assert _build(tmp_path, "a").read_bytes() == _build(tmp_path, "b").read_bytes()


@pytest.mark.skipif(
    not shutil.which("pdftotext"), reason="pdftotext (poppler) not installed"
)
def test_payouts_pdf_keeps_each_section_on_its_own_page(tmp_path):
    blocks = extract.extract(_build(tmp_path, "a"))
    page_of = {
        req: b["loc"]
        for b in blocks
        for req in ("NFR-P1", "NFR-A2", "NFR-S4", "NFR-D4")
        if req in b["text"]
    }
    assert page_of == {"NFR-P1": "p1", "NFR-A2": "p2", "NFR-S4": "p2", "NFR-D4": "p3"}


@pytest.mark.skipif(
    not shutil.which("pdftotext"), reason="pdftotext (poppler) not installed"
)
def test_payouts_pdf_keeps_wrapped_requirements_whole(tmp_path):
    texts = [b["text"] for b in extract.extract(_build(tmp_path, "a"))]
    assert any(
        "restored within 1 hour with no more than 15 minutes of data loss" in t
        for t in texts
    )
